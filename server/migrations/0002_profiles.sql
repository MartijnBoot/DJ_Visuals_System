-- B-02: visual profiles (spec, Data). Additive; 0001 is untouched. The built-in profile is code,
-- not a row (SD8). Row validity is checked on read (`server/src/profiles/store.ts`).
CREATE TABLE profiles (
  id          TEXT PRIMARY KEY,                 -- uuid, generated by the server
  name        TEXT NOT NULL COLLATE NOCASE UNIQUE,
  revision    INTEGER NOT NULL,                 -- starts at 1, +1 per save
  definition  TEXT NOT NULL,                    -- JSON: palette, dials, effects
  created_at  TEXT NOT NULL,                    -- ISO-8601 UTC
  updated_at  TEXT NOT NULL
);
