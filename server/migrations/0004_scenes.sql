-- B-07: scenes (spec SD7, Data; plan PD10). Additive; 0001 to 0003 are untouched. Both modes run
-- it; only a local install reads or writes the table. No sync columns, no tombstones, no link to
-- `profiles`. Row validity is checked on read (`server/src/scenes/store.ts`).
CREATE TABLE scenes (
  id          TEXT PRIMARY KEY,                 -- uuid, generated by the server
  name        TEXT NOT NULL COLLATE NOCASE UNIQUE,
  definition  TEXT NOT NULL,                    -- JSON: profile, dials, feed, transition
  created_at  TEXT NOT NULL,                    -- ISO-8601 UTC
  updated_at  TEXT NOT NULL
);
